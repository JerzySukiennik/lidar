// Dev tool: real clicks and keys. PLAY, pointer lock, walking, stream and pulse, with the fake microphone Chrome provides in tests.
import { createRequire } from 'node:module';
import { homedir } from 'node:os';
const require = createRequire(process.env.PLAYWRIGHT_MODULES || `${homedir()}/openclaw/node_modules/`);
const { chromium } = require('playwright-core');
const OUT = decodeURIComponent(new URL('../shots/', import.meta.url).pathname);
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist', '--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream'] });
const ctx = await browser.newContext({ viewport: { width: 1280, height: 800 }, permissions: ['microphone'] });
const page = await ctx.newPage();
const logs = [];
page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') logs.push(`[${m.type()}] ${m.text()}`); });
page.on('pageerror', (e) => logs.push('pageerror ' + e.message));
await page.goto(process.argv[2] || 'http://localhost:8641/?realm=dev&dpr=1', { waitUntil: 'load' });
await page.waitForFunction(() => window.__ready, null, { timeout: 30000 });
await page.waitForTimeout(5000);
await page.screenshot({ path: OUT + 'final-title.png' });
await page.click('#play');
await page.waitForFunction(() => window.__lidar.game.state === 'play', null, { timeout: 40000 });
await page.waitForTimeout(600);
await page.mouse.click(640, 400);
await page.waitForTimeout(500);
const s0 = await page.evaluate(() => { const g = window.__lidar.game; return { locked: document.pointerLockElement === document.getElementById('view'), paused: document.getElementById('pause').classList.contains('on'), x: g.player.x, z: g.player.z, yaw: g.player.yaw, pts: g.app.cloud.count, mic: g.app.sound.micOn, online: g.app.net.online }; });
await page.keyboard.down('KeyW');
await page.mouse.move(700, 410, { steps: 6 });
await page.waitForTimeout(1200);
await page.keyboard.up('KeyW');
await page.mouse.down({ button: 'left' });
await page.waitForTimeout(900);
await page.mouse.up({ button: 'left' });
await page.mouse.down({ button: 'right' });
await page.waitForTimeout(1500);
await page.mouse.up({ button: 'right' });
await page.waitForTimeout(900);
const s1 = await page.evaluate(() => { const g = window.__lidar.game; return { x: g.player.x, z: g.player.z, yaw: g.player.yaw, pts: g.app.cloud.count, micLevel: +g.app.sound.micLevel.toFixed(2), dpr: g.app.dpr, level: document.getElementById('level').textContent }; });
await page.screenshot({ path: OUT + 'final-game.png' });
console.log('before', JSON.stringify(s0));
console.log('after ', JSON.stringify(s1));
console.log('moved', Math.hypot(s1.x - s0.x, s1.z - s0.z).toFixed(2), 'm, points +', s1.pts - s0.pts);
console.log(logs.slice(0, 8).join('\n'));
await browser.close();
